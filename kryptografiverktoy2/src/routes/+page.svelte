<h1>Kryptografiverktøy</h1>
<p>Velg en krypteringsmetode:</p>

<ul>
	<li><a href="/caesar"><strong>Caesar</strong></a><br />Flytter hver bokstav like mange plasser i alfabetet. Nøkkel: tall fra 0 til 25.</li>
	<li><a href="/vigenere"><strong>Vigenère</strong></a><br />Hver bokstav flyttes etter en nøkkelord som gjentas. Nøkkel: bokstaver A-Z.</li>
	<li><a href="/otp"><strong>One-Time Pad</strong></a><br />Tilfeldig nøkkel som er like lang som teksten og brukes bare én gang.</li>
</ul>

<p><small>Alle metodene bruker det engelske alfabetet (A-Z). Mellomrom beholdes, og tall og spesialtegn er ikke lov.</small></p>

